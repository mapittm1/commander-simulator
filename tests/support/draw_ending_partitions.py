def validate_partitions(registered_classes: tuple[str, ...]) -> None:
    """Reject omitted, repeated or unregistered classes before starting any JVM."""
    selected = Counter(name for classes in PARTITIONS.values() for name in classes)
    registered = Counter(registered_classes)
    if (
        set(PARTITIONS) != set(EXPECTED_COUNTS)
        or any(not classes for classes in PARTITIONS.values())
        or any(count != 1 for count in selected.values())
        or any(count != 1 for count in registered.values())
        or selected != registered
    ):
        raise ValueError(
            "Packaged rules partitions must cover every class exactly once"
        )


def select_partition(name: str, registered_classes: tuple[str, ...]) -> tuple[str, ...]:
    """Allow only the fixed internal group names; never accept arbitrary Java classes."""
    validate_partitions(registered_classes)
    if name not in PARTITIONS:
        raise ValueError("Unknown fixed packaged rules partition")
    return PARTITIONS[name]
